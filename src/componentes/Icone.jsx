export function Icone({ nome, tamanho = 18, colorido = false, className = '', ...props }) {
  const marca = MARCAS[nome]
  if (marca) {
    return (
      <svg
        viewBox="0 0 24 24"
        width={tamanho}
        height={tamanho}
        fill={colorido ? marca.cor : 'currentColor'}
        aria-hidden="true"
        className={`shrink-0 ${className}`}
        {...props}
      >
        <path d={marca.d} />
      </svg>
    )
  }
  const Componente = ICONES[nome] ?? FileStack
  return <Componente size={tamanho} strokeWidth={1.75} aria-hidden="true" className={`shrink-0 ${className}`} {...props} />
}
